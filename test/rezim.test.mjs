import assert from "node:assert/strict";
import fs from "node:fs";
import test from "node:test";

const html = fs.readFileSync(new URL("../site/index.html", import.meta.url), "utf8");
const main = fs.readFileSync(new URL("../site/js/main.js", import.meta.url), "utf8");
const css = fs.readFileSync(new URL("../site/css/site.css", import.meta.url), "utf8");
const opcije = fs.readFileSync(new URL("../site/js/opcije.js", import.meta.url), "utf8");

test("predavanja i samostalni rad", () => {
  assert.match(opcije, /\["predavanja", "Predavanja", "monitor"\]/);
  assert.match(opcije, /\["samostalni", "Samostalni rad", "book-open-text"\]/);
  assert.match(opcije, /\["0\.875", "A−", "Sitniji tekst"\]/);
  assert.match(opcije, /\["1", "A", "Normalan tekst"\]/);
  assert.match(opcije, /\["1\.125", "A\+", "Krupniji tekst"\]/);
  assert.equal(html.includes('id="mod-kontrole"'), false);
  assert.equal(html.includes('id="mod-mesto"'), false);
  assert.equal(html.includes('id="font-kontrole"'), false);
  assert.equal(main.includes("modKontrole"), false);
  assert.equal(main.includes("fontKontrole"), false);
  assert.match(html, /dataset\.mod = mod === "samostalni" \? "samostalni" : "predavanja"/);
  assert.match(html, /localStorage\.getItem\("web-programiranje:stanje"\)/);
  assert.match(html, /zapis\.verzija === 1/);
  assert.match(html, /mod = podesavanja\.mod/);
  assert.match(html, /skala = podesavanja\.font/);
  assert.match(html, /"1\.25": "1\.125"/);
  assert.match(main, /function modPredavanja\(\)/);
  assert.match(main, /function podrazumevaniDeo\(\) \{\n  return modPredavanja\(\) \? "diskusija" : "koraci";\n\}/);
  assert.match(main, /let deo = podrazumevaniDeo\(\)/);
  assert.match(main, /function sakrijPanelSelekcije\(\) \{\n  if \(!modPredavanja\(\)\) return;/);
  assert.match(main, /sakrijPanelSelekcije\(\);\n  if \(location\.hash !== `#cas-\$\{n\}`\)/);
  assert.match(main, /if \(modPredavanja\(\)\) zatvoriMobilIzborSheetove\(\)/);
  assert.match(main, /if \(!uvod && deo !== "editor"\) deo = podrazumevaniDeo\(\)/);
  assert.equal(main.includes("pitalica-samo-ikona"), false);
  assert.equal(css.includes(".pitalica-samo-ikona"), false);
  assert.match(css, /--skala-predavanja:\s*1\.3/);
  assert.match(css, /html\[data-mod="predavanja"\]\s*\{\s*font-size:\s*calc\(16px \* var\(--skala-predavanja\) \* var\(--skala-fonta\)\)/);
  assert.equal(css.includes("#font-kontrole { display: none; }"), false);
  assert.equal(html.includes('data-skala="1.25"'), false);
  assert.equal(html.includes("font-napomena"), false);
  assert.equal(main.includes("dugme.disabled = predavanja"), false);
  assert.match(main, /if \(sacuvan !== sledeci\) lokalno\.promeni\(\(stanje\) => postaviPodesavanje\(stanje, "mod", sledeci\)\)/);
});
